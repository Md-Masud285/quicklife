export const BANGLADESH_DISTRICTS: string[] = BANGLADESH_DISTRICT_COORDINATES.map(d => d.name);

export interface LocationResult {
  success: boolean;
  district?: string;
  lat?: number;
  lng?: number;
  message?: string;
}

class LocationService {
  // Haversine Distance Calculator (km)
  private calculateDistance(lat1: number, lon1: number, lat2: number, lon2: number): number {
    const R = 6371; // Earth radius in km
    const dLat = (lat2 - lat1) * (Math.PI / 180);
    const dLon = (lon2 - lon1) * (Math.PI / 180);
    const a =
      Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos(lat1 * (Math.PI / 180)) *
        Math.cos(lat2 * (Math.PI / 180)) *
        Math.sin(dLon / 2) *
        Math.sin(dLon / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    return R * c;
  }

  // Find Closest Bangladesh District
  public findClosestDistrict(lat: number, lng: number): string {
    let closestDistrict = 'ঢাকা';
    let minDistance = Infinity;

    for (const d of BANGLADESH_DISTRICT_COORDINATES) {
      const distance = this.calculateDistance(lat, lng, d.lat, d.lng);
      if (distance < minDistance) {
        minDistance = distance;
        closestDistrict = d.name;
      }
    }

    return closestDistrict;
  }

  // Get User's Current GPS Location and Nearest District
  public async detectCurrentDistrict(): Promise<LocationResult> {
    if (typeof window === 'undefined' || !navigator.geolocation) {
      return { success: false, message: 'আপনার ব্রাউজার বা ডিভাইসে জিপিএস লোকেশন সাপোর্ট করে না।' };
    }

    return new Promise((resolve) => {
      navigator.geolocation.getCurrentPosition(
        (position) => {
          const lat = position.coords.latitude;
          const lng = position.coords.longitude;
          const district = this.findClosestDistrict(lat, lng);
          resolve({
            success: true,
            district,
            lat,
            lng,
            message: `লোকেশন সনাক্ত হয়েছে: ${district}`
          });
        },
        (error) => {
          let errorMsg = 'লোকেশন পারমিশন পাওয়া যায়নি।';
          if (error.code === error.PERMISSION_DENIED) {
            errorMsg = 'অনুগ্রহ করে ফোনের লোকেশন/GPS পারমিশন চালু করুন।';
          } else if (error.code === error.POSITION_UNAVAILABLE) {
            errorMsg = 'বর্তমানে জিপিএস সিগন্যাল পাওয়া যাচ্ছে না।';
          } else if (error.code === error.TIMEOUT) {
            errorMsg = 'লোকেশন পেতে অতিরিক্ত সময় লাগছে।';
          }
          resolve({ success: false, message: errorMsg });
        },
        { enableHighAccuracy: true, timeout: 10000, maximumAge: 30000 }
      );
    });
  }
}

export const locationService = new LocationService();
